import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const MARKDOWN_ENGINE_PACKAGE = "@jasonbelmonti/markdown-engine";
const EXACT_SEMVER =
  /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-(?:0|[1-9]\d*|[0-9A-Za-z-]*[A-Za-z-][0-9A-Za-z-]*)(?:\.(?:0|[1-9]\d*|[0-9A-Za-z-]*[A-Za-z-][0-9A-Za-z-]*))*)?(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$/;
const scriptPath = fileURLToPath(import.meta.url);
const repositoryRoot = path.resolve(path.dirname(scriptPath), "..");
const defaultManifestPath = path.join(repositoryRoot, "package.json");
const defaultOutputPath = path.join(
  repositoryRoot,
  "src/markdowntrace/generated/release-metadata.ts",
);

function parseArguments(arguments_) {
  const options = {
    check: false,
    manifestPath: defaultManifestPath,
    outputPath: defaultOutputPath,
  };

  for (let index = 0; index < arguments_.length; index += 1) {
    const argument = arguments_[index];

    if (argument === "--check") {
      options.check = true;
      continue;
    }

    if (argument === "--manifest" || argument === "--output") {
      const value = arguments_[index + 1];
      if (value === undefined || value.startsWith("--")) {
        throw new Error(`${argument} requires a path`);
      }

      if (argument === "--manifest") {
        options.manifestPath = path.resolve(value);
      } else {
        options.outputPath = path.resolve(value);
      }
      index += 1;
      continue;
    }

    throw new Error(`unknown argument: ${argument}`);
  }

  return options;
}

async function loadReleaseVersions(manifestPath) {
  let manifest;
  try {
    manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  } catch (error) {
    throw new Error(`cannot read a valid JSON manifest at ${manifestPath}: ${error.message}`);
  }

  if (manifest === null || typeof manifest !== "object" || Array.isArray(manifest)) {
    throw new Error(`manifest at ${manifestPath} must contain a JSON object`);
  }

  const packageVersion = manifest.version;
  const markdownEngineVersion = manifest.dependencies?.[MARKDOWN_ENGINE_PACKAGE];

  assertExactVersion(packageVersion, "package version");
  assertExactVersion(markdownEngineVersion, `${MARKDOWN_ENGINE_PACKAGE} dependency`);

  return { markdownEngineVersion, packageVersion };
}

function assertExactVersion(value, label) {
  if (typeof value !== "string" || !EXACT_SEMVER.test(value)) {
    throw new Error(`${label} must be an exact SemVer value; received ${JSON.stringify(value)}`);
  }
}

function renderReleaseMetadata({ markdownEngineVersion, packageVersion }) {
  return [
    "// Generated by scripts/generate-release-metadata.mjs. Do not edit.",
    `export const MARKDOWN_TRACE_PACKAGE_VERSION = ${JSON.stringify(packageVersion)} as const;`,
    `export const MARKDOWN_ENGINE_PACKAGE_VERSION = ${JSON.stringify(markdownEngineVersion)} as const;`,
    "",
  ].join("\n");
}

async function checkOutput(manifestPath, outputPath, expectedOutput) {
  let actualOutput;
  try {
    actualOutput = await readFile(outputPath, "utf8");
  } catch (error) {
    throw new Error(`generated release metadata is missing at ${outputPath}: ${error.message}`);
  }

  if (actualOutput !== expectedOutput) {
    throw new Error(
      `generated release metadata is stale at ${outputPath}; regenerate it from ${manifestPath}`,
    );
  }

  process.stdout.write(`release metadata is current: ${outputPath}\n`);
}

async function writeOutput(outputPath, output) {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output, "utf8");
  process.stdout.write(`generated release metadata: ${outputPath}\n`);
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const versions = await loadReleaseVersions(options.manifestPath);
  const output = renderReleaseMetadata(versions);

  if (options.check) {
    await checkOutput(options.manifestPath, options.outputPath, output);
  } else {
    await writeOutput(options.outputPath, output);
  }
}

main().catch((error) => {
  process.stderr.write(`release metadata generation failed: ${error.message}\n`);
  process.exitCode = 1;
});
